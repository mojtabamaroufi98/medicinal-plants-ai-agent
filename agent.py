def identify_plant(image_path):

    url = "https://my-api.plantnet.org/v2/identify/all"

    params = {
        "api-key": plantNet_api_key,
        "lang": "en",
        "nb-results": 3
    }

    converted_path = "plantnet_image.jpg"

    try:

        # =========================
        # Convert Image to JPEG
        # =========================

        image = Image.open(image_path)

        # اگر تصویر شفافیت داشته باشد،
        # آن را به RGB تبدیل می‌کنیم
        if image.mode != "RGB":
            image = image.convert("RGB")

        image.save(
            converted_path,
            format="JPEG",
            quality=95
        )

        image.close()

        # =========================
        # Send Image to PlantNet
        # =========================

        with open(
            converted_path,
            "rb"
        ) as image_file:

            files = [
                (
                    "images",
                    (
                        "plant.jpg",
                        image_file,
                        "image/jpeg"
                    )
                )
            ]

            data = {
                "organs": "auto"
            }

            response = requests.post(
                url,
                params=params,
                files=files,
                data=data,
                timeout=30
            )

        # =========================
        # Check Response
        # =========================

        if response.status_code != 200:

            return {
                "error": (
                    f"PlantNet Error "
                    f"{response.status_code}\n"
                    f"{response.text}"
                )
            }

        result = response.json()

    except FileNotFoundError:

        return {
            "error": "فایل تصویر پیدا نشد."
        }

    except Exception as error:

        return {
            "error": (
                f"خطا در پردازش تصویر:\n"
                f"{error}"
            )
        }

    # =========================
    # Extract Results
    # =========================

    plants = []

    for item in result.get(
        "results",
        []
    ):

        species = item.get(
            "species",
            {}
        )

        plants.append({
            "scientific_name": species.get(
                "scientificNameWithoutAuthor"
            ),

            "common_names": species.get(
                "commonNames",
                []
            ),

            "confidence": item.get(
                "score"
            )
        })

    return {
        "best_match": result.get(
            "bestMatch"
        ),

        "plants": plants
    }



